    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        int filaSeleccionada = cargarReservas.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(null,
                    "Por favor, seleccione una reserva de la tabla.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idReserva = (int) cargarReservas.getValueAt(filaSeleccionada, 0);
        String estadoActual = (String) cargarReservas.getValueAt(filaSeleccionada, 5);

        if (!"pendiente".equalsIgnoreCase(estadoActual)) {
            JOptionPane.showMessageDialog(null,
                    "Solo se pueden aprobar reservas que estén en estado 'pendiente'.",
                    "Aviso", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        ReservaController controller = new ReservaController();
        boolean exito = controller.aprobarReserva(idReserva);

        if (exito) {
            JOptionPane.showMessageDialog(null,
                    "¡Reserva aprobada con éxito!",
                    "Éxito", JOptionPane.INFORMATION_MESSAGE);

            listarReservas();
        } else {
            JOptionPane.showMessageDialog(null,
                    "No se pudo aprobar la reserva.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAceptarActionPerformed

    private void btnRechazarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRechazarActionPerformed
        int filaSeleccionada = cargarReservas.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(null,
                    "Por favor, seleccione una reserva de la tabla.",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Obtener el ID de la reserva (columna 0)
        int idReserva = (int) cargarReservas.getValueAt(filaSeleccionada, 0);

        // 3. Instanciar el controlador y rechazar la reserva
        ReservaController controller = new ReservaController();
        boolean exito = controller.rechazarReserva(idReserva);

        if (exito) {
            JOptionPane.showMessageDialog(null,
                    "Reserva rechazada correctamente.",
                    "Éxito", JOptionPane.INFORMATION_MESSAGE);

            // 4. Recargar la tabla para reflejar el cambio de estado en la interfaz
            listarReservas();
        } else {
            JOptionPane.showMessageDialog(null,
                    "No se pudo rechazar la reserva. Verifique que esté en estado 'pendiente'.",
                    "Aviso", JOptionPane.WARNING_MESSAGE);
        }
     }//GEN-LAST:event_btnRechazarActionPerformed

