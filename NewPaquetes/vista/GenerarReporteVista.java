    private void enviarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_enviarReporteActionPerformed
        if (usuario == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo identificar al usuario.");
            return;
        }

        String nombreEquipo = (String) cmbEquipos.getSelectedItem();

        if (nombreEquipo == null) {
            JOptionPane.showMessageDialog(this,
                    "Seleccioná un equipo.");
            return;
        }

        String descripcion = txtDescripcion.getText().trim();

        if (descripcion.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingresá una descripción de la falla.");
            return;
        }

        negocio.EquipoService equipoService
                = new negocio.EquipoService();

        java.util.ArrayList<modelo.Equipo> equipos
                = equipoService.listarEquipos();

        int idEquipo = -1;

        for (modelo.Equipo equipo : equipos) {
            if (equipo.getNombre().equals(nombreEquipo)) {
                idEquipo = equipo.getIdEquipo();
                break;
            }
        }

        if (idEquipo == -1) {
            JOptionPane.showMessageDialog(this,
                    "No se encontró el equipo seleccionado.");
            return;
        }

        boolean registrado = reporteController.registrarReporte(
                usuario.getidUsuario(),
                idEquipo,
                descripcion
        );

        if (registrado) {
            JOptionPane.showMessageDialog(this,
                    "Reporte registrado correctamente.");

            txtDescripcion.setText("");

        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar el reporte.");
        }
    }//GEN-LAST:event_enviarReporteActionPerformed

