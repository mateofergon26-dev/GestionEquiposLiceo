    private void cargarReservas() {

        reservasDisponibles = reservaService.listarAprobadasSinPrestamo();

        jComboBox1.removeAllItems();

        for (Reserva reserva : reservasDisponibles) {
            jComboBox1.addItem(
                    "Reserva " + reserva.getIdReserva()
                    + " - " + reserva.getNombreEquipo()
            );
        }

        if (reservasDisponibles.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No hay reservas aprobadas pendientes de préstamo.");
        }
    }

