    private void btnRegistrarDevolucionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarDevolucionActionPerformed
        int fila = tablaPrestamos.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un préstamo.");
            return;
        }

        int idPrestamo = (int) tablaPrestamos.getValueAt(fila, 0);

        int confirmar = JOptionPane.showConfirmDialog(this,
                "¿Desea registrar la devolución de este préstamo?",
                "Confirmar devolución",
                JOptionPane.YES_NO_OPTION);

        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        String[] opciones = {
            "Sin incidencia",
            "Retraso",
            "Daño"
        };

        int seleccion = JOptionPane.showOptionDialog(this,
                "¿El equipo presenta alguna incidencia?",
                "Incidencias",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[0]);

        if (seleccion == -1) {
            return;
        }

        String tipoIncidencia = null;
        String descripcion = null;

        if (seleccion == 1) {
            tipoIncidencia = "retraso";
            descripcion = JOptionPane.showInputDialog(this,
                    "Describa el retraso (opcional):");
        } else if (seleccion == 2) {
            tipoIncidencia = "dano";
            descripcion = JOptionPane.showInputDialog(this,
                    "Describa el daño (opcional):");
        }

        String resultado = prestamoController.registrarDevolucion(
                idPrestamo,
                tipoIncidencia,
                descripcion
        );

        if (resultado == null) {

            JOptionPane.showMessageDialog(this,
                    "Devolución registrada correctamente.");

            cargarPrestamos();

        } else {

            JOptionPane.showMessageDialog(this, resultado);
        }
    }//GEN-LAST:event_btnRegistrarDevolucionActionPerformed

