    private void cargarPrestamos() {

        DefaultTableModel modelo = new DefaultTableModel();

        modelo.addColumn("ID préstamo");
        modelo.addColumn("ID reserva");
        modelo.addColumn("ID equipo");
        modelo.addColumn("Fecha de entrega");
        modelo.addColumn("Fecha devolución esperada");
        modelo.addColumn("Estado");

        prestamos = prestamoController.listarPrestamos();

        for (Prestamo prestamo : prestamos) {

            if (!prestamo.getEstado().equals("devuelto")) {

                Object[] fila = {
                    prestamo.getIdPrestamo(),
                    prestamo.getIdReserva(),
                    prestamo.getIdEquipo(),
                    prestamo.getFechaEntregaReal(),
                    prestamo.getFechaDevolucionEsperada(),
                    prestamo.getEstado()
                };

                modelo.addRow(fila);
            }
        }

        tablaPrestamos.setModel(modelo);

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "No hay préstamos pendientes de devolución.");
        }
    }

