    private void cargarReportes() {

        modeloTabla.setRowCount(0);

        List<ReporteFalla> reportes = controlador.listarReportes();

        for (ReporteFalla reporte : reportes) {

            modeloTabla.addRow(new Object[]{
                reporte.getIdReporte(),
                reporte.getFechaReporte(),
                reporte.getIdUsuario(),
                reporte.getIdEquipo(),
                reporte.getDescripcionFalla(),
                reporte.getEstado()
            });
        }
    }

    private void cargarDescripcion() {

        int fila = tablaReportes.getSelectedRow();

        if (fila < 0) {
            txtDescripcion.setText("");
            return;
        }

        txtDescripcion.setText(
                modeloTabla.getValueAt(fila, 4).toString()
        );

        cmbEstado.setSelectedItem(
                modeloTabla.getValueAt(fila, 5).toString()
        );
    }

