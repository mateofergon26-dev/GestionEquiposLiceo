    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
  
        int fila = tablaReportes.getSelectedRow();

    if (fila < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Seleccione un reporte de la tabla.");
        return;
    }

    int idReporte = Integer.parseInt(
            modeloTabla.getValueAt(fila, 0).toString());

    String nuevoEstado = cmbEstado.getSelectedItem().toString();

    int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Desea cambiar el estado de este reporte?",
            "Confirmar actualización",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    boolean resultado = controlador.actualizarEstado(
            idReporte, nuevoEstado);

    if (resultado) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Estado del reporte actualizado correctamente.");

        cargarReportes();
        txtDescripcion.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(this,
                "No se pudo actualizar el reporte.");
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

