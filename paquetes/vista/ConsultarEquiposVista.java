    private void cargarEquipos() {
        javax.swing.table.DefaultTableModel modelo
                = (javax.swing.table.DefaultTableModel) tablaEquipos.getModel();

        modelo.setRowCount(0);

        negocio.EquipoService servicio = new negocio.EquipoService();

        try {
            java.util.ArrayList<modelo.Equipo> equipos
                    = servicio.listarEquipos();

            for (modelo.Equipo equipo : equipos) {
                modelo.addRow(new Object[]{
                    equipo.getIdEquipo(),
                    equipo.getNombre(),
                    equipo.getTipo(),
                    equipo.getNumeroSerie(),
                    equipo.getEstado(),
                    equipo.getUbicacion()
                });
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error al cargar los equipos: " + e.getMessage()
            );
        }
    }

